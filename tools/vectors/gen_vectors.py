#!/usr/bin/env python3
"""Independent reference generator for pvault known-answer test vectors.

This script never runs pvault code. It computes pvault-specific vectors with
independent implementations (OpenSSL through `cryptography`, libsodium through
`PyNaCl`, and the Argon2 reference implementation through `argon2-cffi`), and
converts published vectors (Wycheproof, RFC 4231, RFC 9106) into a simple
line-based format that the Rust tests read.

Usage (development only, inside an isolated virtual environment):

    python3 -m venv /tmp/pvault-vectors
    /tmp/pvault-vectors/bin/pip install -r tools/vectors/requirements.txt
    /tmp/pvault-vectors/bin/python tools/vectors/gen_vectors.py \
        --wycheproof DIR --rfc DIR --out crates/pvault-core/testdata

DIR for --wycheproof holds the four Wycheproof files listed in WYCHEPROOF_FILES,
taken from commit WYCHEPROOF_COMMIT. DIR for --rfc holds rfc4231.txt and
rfc9106.txt from rfc-editor.org. Every input is checked against a pinned SHA-256
before use.
"""

import argparse
import hashlib
import hmac
import json
import platform
import re
import struct
import sys
from importlib import metadata
from pathlib import Path

import argon2.low_level as argon2_ll
import nacl.bindings as sodium
from cryptography.hazmat.backends.openssl import backend as openssl_backend
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.ciphers.aead import AESGCMSIV
from cryptography.hazmat.primitives.kdf.hkdf import HKDF

WYCHEPROOF_COMMIT = "3fa63dd0344abb611f1fb1d77e119938603ea230"
WYCHEPROOF_URL = "https://github.com/C2SP/wycheproof/blob/" + WYCHEPROOF_COMMIT
WYCHEPROOF_FILES = {
    "hkdf_sha512_test.json": None,
    "hmac_sha512_test.json": None,
    "aes_gcm_siv_test.json": None,
    "xchacha20_poly1305_test.json": None,
}
RFC_FILES = {
    "rfc4231.txt": "72178527ce93500e730bc8eb182b857e583096d652b64ece0879c52ba1df973b",
    "rfc9106.txt": "855c06f060379e34285e83a217e9069b5c72e161a1e54df9af5cd88dbb231f31",
}
PINNED_WYCHEPROOF_SHA256 = {
    # Filled from the files at WYCHEPROOF_COMMIT; checked on every run.
    "hkdf_sha512_test.json": "bb9a21f4e86041caf5d7792b030349f8ff289087f195b2fbc0fc0afc39deca6f",
    "hmac_sha512_test.json": "b6c90477bdb4a6fc8ee3d1f7b2c0b69a8dfffab34718abaa6cabd71cc2ba1207",
    "aes_gcm_siv_test.json": "d96e4f8c0db1a5e3b395907120f9d417d599507e7a08a1f60babff09ae276a8d",
    "xchacha20_poly1305_test.json": "a79de072571b90eb40c3a63ce0c7f75dcb4b62323c8870228e1f61dcc61d63a9",
}

PACKAGES = ["cryptography", "PyNaCl", "argon2-cffi", "argon2-cffi-bindings"]


def sha256_file(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def check_pinned(path, expected):
    actual = sha256_file(path)
    if expected and actual != expected:
        sys.exit(f"{path}: SHA-256 {actual} does not match pinned {expected}")
    return actual


def provenance_header(lines):
    versions = ", ".join(f"{p} {metadata.version(p)}" for p in PACKAGES)
    head = [
        "# Generated by tools/vectors/gen_vectors.py. Do not edit by hand.",
        f"# Python {platform.python_version()}; {versions}",
        f"# {openssl_backend.openssl_version_text()}",
    ]
    return "\n".join(head + [f"# {line}" for line in lines]) + "\n"


def write_records(path, header_lines, records):
    out = [provenance_header(header_lines)]
    for record in records:
        out.append("\n")
        for key, value in record:
            out.append(f"{key} = {value}\n")
    Path(path).write_text("".join(out))


# ---------------------------------------------------------------------------
# Wycheproof (published vectors, converted)
# ---------------------------------------------------------------------------


def wycheproof(path, digest, select):
    data = json.loads(Path(path).read_text())
    records, skipped = [], 0
    for group in data["testGroups"]:
        for test in group["tests"]:
            record = select(group, test)
            if record is None:
                skipped += 1
            else:
                records.append(record)
    header = [
        f"Converted from Wycheproof {Path(path).name} ({data['algorithm']}),",
        f"commit {WYCHEPROOF_COMMIT}, file SHA-256 {digest}.",
        f"Source: {WYCHEPROOF_URL}/testvectors_v1/{Path(path).name}",
        "Licensed under the Apache License 2.0 (third_party/wycheproof/LICENSE).",
        "Changes: format converted to key = value records; only the subset that",
        f"matches pvault's use is kept ({len(records)} kept, {skipped} skipped).",
    ]
    return header, records


def select_hkdf(group, test):
    return [
        ("tcId", str(test["tcId"])),
        ("result", test["result"]),
        ("ikm", test["ikm"]),
        ("salt", test["salt"]),
        ("info", test["info"]),
        ("size", str(test["size"])),
        ("okm", test["okm"]),
    ]


def select_hmac(group, test):
    if group["tagSize"] != 512:
        return None
    if test["result"] == "valid":
        mac = hmac.new(bytes.fromhex(test["key"]), bytes.fromhex(test["msg"]), "sha512")
        assert mac.hexdigest() == test["tag"], test["tcId"]
    return [
        ("tcId", str(test["tcId"])),
        ("result", test["result"]),
        ("key", test["key"]),
        ("msg", test["msg"]),
        ("tag", test["tag"]),
    ]


def select_aead(key_bits, iv_bits):
    def select(group, test):
        if group["keySize"] != key_bits or group["ivSize"] != iv_bits or group["tagSize"] != 128:
            return None
        return [
            ("tcId", str(test["tcId"])),
            ("result", test["result"]),
            ("key", test["key"]),
            ("iv", test["iv"]),
            ("aad", test["aad"]),
            ("msg", test["msg"]),
            ("ct", test["ct"]),
            ("tag", test["tag"]),
        ]

    return select


# ---------------------------------------------------------------------------
# RFC 4231 (HMAC-SHA-512) and RFC 9106 (Argon2id), parsed from the RFC text
# ---------------------------------------------------------------------------


FIELD = re.compile(r"^   (Key|Data|HMAC-SHA-512)\s*=?\s+([0-9a-f]+)")
CONTINUATION = re.compile(r"^ {18}([0-9a-f]+)")


def parse_rfc4231(text):
    cases = re.split(r"\n4\.\d+\.  Test Case (\d+)\n", text)
    records = []
    for number, body in zip(cases[1::2], cases[2::2]):
        fields, current = {}, None
        for line in body.splitlines():
            match = FIELD.match(line)
            if match:
                current = match.group(1)
                fields[current] = match.group(2)
                continue
            match = CONTINUATION.match(line)
            if match and current:
                fields[current] += match.group(1)
            else:
                current = None
        if number == "5":
            continue  # truncated output; pvault always uses full 512-bit tags
        key, data, tag = (bytes.fromhex(fields[k]) for k in ("Key", "Data", "HMAC-SHA-512"))
        assert hmac.new(key, data, "sha512").digest() == tag, f"RFC 4231 case {number}"
        records.append([("case", number), ("key", key.hex()), ("data", data.hex()), ("tag", tag.hex())])
    assert [r[0][1] for r in records] == ["1", "2", "3", "4", "6", "7"], records
    return records


def parse_rfc9106_argon2id(text):
    # The heading also appears in the table of contents; the section body is
    # the last occurrence, and must declare Argon2id version 19.
    section = text.rsplit("5.3.  Argon2id Test Vectors", 1)[1].split("\n6.  ", 1)[0]
    assert "Argon2id version number 19" in section.split("Memory:", 1)[0], "wrong section"

    def hexfield(label, end):
        raw = section.split(label, 1)[1].split(end, 1)[0]
        return bytes.fromhex("".join(re.findall(r"\b[0-9a-f]{2}\b", raw)))

    record = [
        ("m_kib", "32"),
        ("t", "3"),
        ("p", "4"),
        ("password", hexfield("Password[32]:", "Salt").hex()),
        ("salt", hexfield("Salt[16]:", "Secret").hex()),
        ("secret", hexfield("Secret[8]:", "Associated").hex()),
        ("ad", hexfield("Associated data[12]:", "Pre-hashing").hex()),
        ("tag", hexfield("Tag:", "\n\n").hex()),
    ]
    lengths = {k: len(v) // 2 for k, v in record[3:]}
    assert lengths == {"password": 32, "salt": 16, "secret": 8, "ad": 12, "tag": 32}, lengths
    return record


# ---------------------------------------------------------------------------
# pvault-specific vectors (spec 5.1 and 7.7), computed independently
# ---------------------------------------------------------------------------


KDF_LABELS = [
    ("s1_wrap", b"pvault/v1/s1-wrap"),
    ("s2_wrap", b"pvault/v1/s2-wrap"),
    ("tpm_auth", b"pvault/v1/tpm-auth"),
    ("portable_slot", b"pvault/v1/portable-slot"),
    ("duress", b"pvault/v1/duress"),
]


def hkdf_sha512(ikm, info, length=32):
    return HKDF(algorithm=hashes.SHA512(), length=length, salt=None, info=info).derive(ikm)


def kdf_vector(passphrase, salt, m_kib, t, p, k_mac):
    master = argon2_ll.hash_secret_raw(
        secret=passphrase.encode("utf-8"),
        salt=salt,
        time_cost=t,
        memory_cost=m_kib,
        parallelism=p,
        hash_len=32,
        type=argon2_ll.Type.ID,
        version=19,
    )
    record = [
        ("passphrase_utf8", passphrase.encode("utf-8").hex()),
        ("salt", salt.hex()),
        ("m_kib", str(m_kib)),
        ("t", str(t)),
        ("p", str(p)),
        ("master_pw", master.hex()),
    ]
    record += [(name, hkdf_sha512(master, info).hex()) for name, info in KDF_LABELS]
    record += [("k_mac", k_mac.hex()), ("journal_key", hkdf_sha512(k_mac, b"pvault/v1/journal").hex())]
    return record


CHUNK = 65536
MAGICS = {"object": b"PVOB", "keytable": b"PVKT"}


def chunk_nonces(i):
    n1 = bytes((0x10 + i + j) % 256 for j in range(12))
    n2 = bytes((0x80 + 3 * i + j) % 256 for j in range(24))
    return n1, n2


def stream_vector(name, kind, stream_id, context, plain_size, key_aes, key_chacha):
    magic = MAGICS[kind]
    plaintext = bytes((j * 31 + 7) % 256 for j in range(plain_size))
    chunk_count = max(1, -(-plain_size // CHUNK))
    out = bytearray(magic + struct.pack(">H", 1) + stream_id + struct.pack(">QQ", context, plain_size))
    nonces = []
    for i in range(chunk_count):
        chunk = plaintext[i * CHUNK : (i + 1) * CHUNK]
        is_last = 1 if i == chunk_count - 1 else 0
        aad = (
            b"pvault/v1/"
            + magic
            + struct.pack(">H", 1)
            + stream_id
            + struct.pack(">QQQQB", context, plain_size, chunk_count, i, is_last)
        )
        n1, n2 = chunk_nonces(i)
        c1 = AESGCMSIV(key_aes).encrypt(n1, chunk, aad)
        c2 = sodium.crypto_aead_xchacha20poly1305_ietf_encrypt(n1 + c1, aad, n2, key_chacha)
        out += struct.pack(">I", 24 + len(c2)) + n2 + c2
        nonces.append(n1.hex() + n2.hex())
    stream = bytes(out)
    record = [
        ("name", name),
        ("kind", kind),
        ("key_aes", key_aes.hex()),
        ("key_chacha", key_chacha.hex()),
        ("stream_id", stream_id.hex()),
        ("context", str(context)),
        ("plain_size", str(plain_size)),
        ("plaintext_pattern", "byte j = (31 * j + 7) mod 256"),
        ("nonces", ",".join(nonces)),
        ("stream_len", str(len(stream))),
        ("stream_sha256", hashlib.sha256(stream).hexdigest()),
    ]
    if len(stream) <= 4096:
        record.append(("stream", stream.hex()))
    return record


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--wycheproof", required=True, type=Path)
    parser.add_argument("--rfc", required=True, type=Path)
    parser.add_argument("--out", required=True, type=Path)
    args = parser.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)

    digests = {}
    for name in WYCHEPROOF_FILES:
        digests[name] = check_pinned(args.wycheproof / name, PINNED_WYCHEPROOF_SHA256[name])
    for name, expected in RFC_FILES.items():
        check_pinned(args.rfc / name, expected)

    conversions = [
        ("hkdf_sha512_test.json", "wycheproof_hkdf_sha512.txt", select_hkdf),
        ("hmac_sha512_test.json", "wycheproof_hmac_sha512.txt", select_hmac),
        ("aes_gcm_siv_test.json", "wycheproof_aes256_gcm_siv.txt", select_aead(256, 96)),
        ("xchacha20_poly1305_test.json", "wycheproof_xchacha20_poly1305.txt", select_aead(256, 192)),
    ]
    for source, target, select in conversions:
        header, records = wycheproof(args.wycheproof / source, digests[source], select)
        write_records(args.out / target, header, records)

    rfc4231 = (args.rfc / "rfc4231.txt").read_text()
    write_records(
        args.out / "rfc4231_hmac_sha512.txt",
        [
            f"Parsed from RFC 4231 section 4 (rfc4231.txt SHA-256 {RFC_FILES['rfc4231.txt']}).",
            "Each tag was re-verified with Python's hmac module. Test Case 5 is omitted",
            "(truncated output).",
        ],
        parse_rfc4231(rfc4231),
    )

    rfc9106 = (args.rfc / "rfc9106.txt").read_text()
    write_records(
        args.out / "rfc9106_argon2id.txt",
        [
            f"Parsed from RFC 9106 section 5.3 (rfc9106.txt SHA-256 {RFC_FILES['rfc9106.txt']}).",
            "Argon2id, version 0x13. Uses a secret and associated data, so it checks the",
            "argon2 crate directly; pvault itself never uses either input.",
        ],
        [parse_rfc9106_argon2id(rfc9106)],
    )

    write_records(
        args.out / "pvault_kdf.txt",
        [
            "pvault spec 7.1, section 5.1: Argon2id (v0x13, no secret, no associated data,",
            "32-byte output) followed by HKDF-SHA-512 (no salt, L = 32).",
            "Computed with argon2-cffi (Argon2 reference implementation) and",
            "cryptography (OpenSSL) HKDF.",
        ],
        [
            kdf_vector(
                "abacus abdomen abdominal abide abiding ability ablaze able abnormal abrasion abrasive abreast",
                bytes(range(32)),
                262144,
                3,
                4,
                bytes(range(64, 96)),
            ),
            kdf_vector(
                "zoom zone zoning zookeeper zoologist zoology yo-yo t-shirt",
                bytes(range(32, 64)),
                262144,
                4,
                1,
                bytes(range(96, 128)),
            ),
        ],
    )

    key_aes = bytes(range(0x20, 0x40))
    key_chacha = bytes(range(0x40, 0x60))
    object_id = bytes(range(0xA0, 0xB0))
    vault_id = bytes(range(0xC0, 0xD0))
    write_records(
        args.out / "pvault_stream.txt",
        [
            "pvault spec 7.1, section 7.7 chunked format with fixed keys and nonces.",
            "Inner layer: AES-256-GCM-SIV (cryptography / OpenSSL).",
            "Outer layer: XChaCha20-Poly1305 (PyNaCl / libsodium).",
            "nonces: one entry per chunk, n1 (12 bytes) followed by n2 (24 bytes), hex.",
        ],
        [
            stream_vector("object-empty", "object", object_id, 0, 0, key_aes, key_chacha),
            stream_vector("object-1", "object", object_id, 0, 1, key_aes, key_chacha),
            stream_vector("object-64k", "object", object_id, 0, CHUNK, key_aes, key_chacha),
            stream_vector("object-64k-plus-1", "object", object_id, 0, CHUNK + 1, key_aes, key_chacha),
            stream_vector("keytable-100", "keytable", vault_id, 7, 100, key_aes, key_chacha),
        ],
    )


if __name__ == "__main__":
    main()
