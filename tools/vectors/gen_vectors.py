def sha256_file(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def check_pinned(path, expected):
    actual = sha256_file(path)
    if expected and actual != expected:
        sys.exit(f"{path}: SHA-256 {actual} does not match pinned {expected}")
    return actual


def provenance_header(lines):
    versions = ", ".join(f"{p} {metadata.version(p)}" for p in PACKAGES)
    head = [
        "# Generated by tools/vectors/gen_vectors.py. Do not edit by hand.",
        f"# Python {platform.python_version()}; {versions}",
        f"# {openssl_backend.openssl_version_text()}",
    ]
    return "\n".join(head + [f"# {line}" for line in lines]) + "\n"


def write_records(path, header_lines, records):
    out = [provenance_header(header_lines)]
    for record in records:
        out.append("\n")
        for key, value in record:
            out.append(f"{key} = {value}\n")
    Path(path).write_text("".join(out))


